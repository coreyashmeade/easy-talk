#!/usr/bin/env python3 -I
"""Generate app/Sources/EasyTalkCore/ModelManifest.swift: pinned model files + SHA-256 (PRD R40).
Run after a trusted first download. Usage: scripts/make-model-manifest.py"""
import hashlib, os, pathlib, sys
HOME = pathlib.Path.home()
MODELS = [
    ("qwen", "mlx-community/Qwen3.5-4B-MLX-4bit", "32f3e8ecf65426fc3306969496342d504bfa13f3",
     HOME / ".cache/huggingface/hub/models--mlx-community--Qwen3.5-4B-MLX-4bit/snapshots/32f3e8ecf65426fc3306969496342d504bfa13f3"),
    ("parakeet", "FluidInference/parakeet-tdt-0.6b-v2-coreml", "ee09c569f73759e6d44c9bd16766f477b2b36d39",
     HOME / "Library/Application Support/FluidAudio/Models/parakeet-tdt-0.6b-v2-coreml"),
]
def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""): h.update(chunk)
    return h.hexdigest()
out = ["// Generated by scripts/make-model-manifest.py. Do not edit by hand.",
       "// Pinned model files and SHA-256 checksums (PRD R40).", "",
       "public enum ModelManifest {"]
for key, repo, rev, root in MODELS:
    files = sorted(str(p.relative_to(root)) for p in root.rglob("*") if p.is_file() or (p.is_symlink() and p.resolve().is_file()))
    total = 0
    out.append(f"    public static let {key} = PinnedModel(")
    out.append(f'        repo: "{repo}",\n        revision: "{rev}",\n        files: [')
    for rel in files:
        p = (root / rel).resolve(); size = p.stat().st_size; total += size
        out.append(f'            PinnedFile(path: "{rel}", sha256: "{sha(p)}", size: {size}),')
        print(key, rel, size, file=sys.stderr)
    out.append("        ])")
    print(f"{key}: {len(files)} files, {total/1e9:.2f} GB", file=sys.stderr)
out.append("}")
dest = pathlib.Path(__file__).resolve().parent.parent / "app/Sources/EasyTalkCore/ModelManifest.swift"
dest.write_text("\n".join(out) + "\n")
print("wrote", dest, file=sys.stderr)
